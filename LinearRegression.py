gas_df = pd.DataFrame(gas_data)

x_gas = gas_df[["Kilometers"]]
y_gas = gas_df[["Liters"]]
gas_model = LinearRegression()
gas_model.fit(x_gas, y_gas)

price_per_liter = 15000

def calculateGasoline(km):
    prediction = gas_model.predict([[km]])
    liters = prediction[0][0]
    cost = liters * price_per_liter
    co2 = liters * 2.31
    return round(liters, 2), round(cost, 2), round(co2, 2)

def generateGasolineChart(km):
    prediction = gas_model.predict([[km]])
    liters = prediction[0][0]

    x_min = min(gas_df["Kilometers"].min(), km)
    x_max = max(gas_df["Kilometers"].max(), km)
    y_min = min(gas_df["Liters"].min(), liters)
    y_max = max(gas_df["Liters"].max(), liters)

    x_pad = (x_max - x_min) * 0.1 if x_max > x_min else 1
    y_pad = (y_max - y_min) * 0.1 if y_max > y_min else 1

    line_x = [x_min, x_max]
    line_y = gas_model.predict([[line_x[0]], [line_x[1]]])

    plt.figure(figsize=(6, 4))
    plt.scatter(gas_df["Kilometers"], gas_df["Liters"], color="#7fb08f", alpha=0.4, s=15, label="Training data")
    plt.plot(line_x, line_y, color="#e0a872", linewidth=2, label="Regression line")
    plt.scatter([km], [liters], color="#2f9e6f", s=100, zorder=5, label="Prediction")
    plt.xlim(x_min - x_pad, x_max + x_pad)
    plt.ylim(y_min - y_pad, y_max + y_pad)
    plt.xlabel("Kilometers")
    plt.ylabel("Liters")
    plt.title("Gasoline Consumption Prediction")
    plt.legend()

    img = io.BytesIO()
    plt.savefig(img, format='png')
    plt.close()
    img.seek(0)
    return base64.b64encode(img.getvalue()).decode('utf-8')