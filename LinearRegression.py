df_grades = pd.DataFrame(data_grades)
x_grades = df_grades[["Study Hours"]]
y_grades = df_grades[["Final Grade"]]
model_grades = LinearRegression()
model_grades.fit(x_grades, y_grades)

def calculateGrade(hours):
    prediction = model_grades.predict([[hours]])
    result = prediction[0][0]
    return round(result, 2)

def generarGraficaNotas(hours):
    prediction = model_grades.predict([[hours]])
    valor = prediction[0][0]

    x_min = min(df_grades["Study Hours"].min(), hours)
    x_max = max(df_grades["Study Hours"].max(), hours)
    y_min = min(df_grades["Final Grade"].min(), valor)
    y_max = max(df_grades["Final Grade"].max(), valor)

    x_pad = (x_max - x_min) * 0.1 if x_max > x_min else 1
    y_pad = (y_max - y_min) * 0.1 if y_max > y_min else 1

    line_x = [x_min, x_max]
    line_y = model_grades.predict([[line_x[0]], [line_x[1]]])

    plt.figure(figsize=(6, 4))
    plt.scatter(df_grades["Study Hours"], df_grades["Final Grade"], color="#7fb08f", alpha=0.4, s=15, label="Training data")
    plt.plot(line_x, line_y, color="#e0a872", linewidth=2, label="Regression line")
    plt.scatter([hours], [valor], color="#2f9e6f", s=100, zorder=5, label="Prediction")
    plt.xlim(x_min - x_pad, x_max + x_pad)
    plt.ylim(y_min - y_pad, y_max + y_pad)
    plt.xlabel("Study Hours")
    plt.ylabel("Final Grade")
    plt.title("Grade Prediction")
    plt.legend()

    img = io.BytesIO()
    plt.savefig(img, format='png')
    plt.close()
    img.seek(0)
    return base64.b64encode(img.getvalue()).decode('utf-8')

